// Local assets + stubbed APIs only. No email, paid generation or account changes.
import {readFileSync, existsSync} from 'node:fs';
import assert from 'node:assert/strict';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = new URL('../', import.meta.url);
const browser = await chromium.launch({executablePath:process.env.CHROME_BIN, headless:true, args:['--no-sandbox']});
let mutations = 0;
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/*', async route => {
    const req = route.request(), url = new URL(req.url());
    if (!['GET','HEAD'].includes(req.method())) mutations++;
    if (url.origin !== 'https://geniemadeit.com') return route.fulfill({body:''});
    if (url.pathname.startsWith('/api/')) return route.fulfill({contentType:'application/json',body:JSON.stringify({ok:true,packs:[],plans:[],items:[]})});
    const local = url.pathname === '/' ? 'index.html' : url.pathname === '/ai-influencer' ? 'ai-influencer.html' : url.pathname.slice(1);
    const file = new URL(local,root);
    if (!existsSync(file)) return route.fulfill({status:404,body:'not found'});
    const contentType = local.endsWith('.html') ? 'text/html' : local.endsWith('.css') ? 'text/css' : local.endsWith('.js') ? 'application/javascript' : local.endsWith('.png') ? 'image/png' : 'application/octet-stream';
    return route.fulfill({contentType,body:readFileSync(file)});
  });
  await page.goto('https://geniemadeit.com/');
  await page.locator('.influencer-promo img').waitFor();
  assert.equal(await page.locator('.influencer-promo img').evaluate(el=>el.complete && el.naturalWidth>0),true);
  await page.screenshot({path:'/tmp/geniemade-influencer-home-desktop.png',fullPage:true});
  await page.getByRole('link',{name:'Create your AI influencer →',exact:true}).click();
  await page.getByRole('heading',{name:'Create a realistic AI influencer.'}).waitFor();
  assert.equal(await page.locator('link[rel=canonical]').getAttribute('href'),'https://geniemadeit.com/ai-influencer');
  assert.equal(await page.locator('.ai-hero img').evaluate(el=>el.complete && el.naturalWidth>0),true);
  assert.match(await page.locator('#services').innerText(),/Custom quote/);
  assert.doesNotMatch(await page.locator('#page-title').innerText(),/Maya/);
  const service = JSON.parse(await page.locator('script[type="application/ld+json"]').first().textContent());
  assert.equal(service['@type'],'Service');assert.equal(service.offers,undefined);
  await page.getByText('Can I create a realistic AI influencer like Maya Lanez?',{exact:true}).click();
  assert.match(await page.locator('#questions').innerText(),/not affiliated with/);
  await page.getByText('Can I create a realistic AI influencer like Maya Lanez?',{exact:true}).click();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'/tmp/geniemade-influencer-desktop.png',fullPage:true});
  await page.screenshot({path:'/tmp/geniemade-influencer-desktop-hero.png'});
  await page.getByRole('button',{name:'Prepare my consultation brief →'}).click();
  assert.equal(await page.locator('#brief-result').isHidden(),true);
  await page.locator('[name=brand]').fill('Test Brand & Co');
  await page.locator('[name=identity]').selectOption({label:'An original fictional adult character'});
  await page.locator('[name=goal]').fill('Original character for a café launch. <script>not executable</script>');
  await page.getByRole('button',{name:'Prepare my consultation brief →'}).click();
  assert.equal(await page.locator('#brief-result').isVisible(),true);
  assert.match(await page.locator('#brief-status').innerText(),/Nothing has been sent/);
  const mail = new URL(await page.locator('#brief-email').getAttribute('href'));
  assert.equal(mail.protocol,'mailto:');assert.equal(mail.pathname,'support@geniemadeit.com');
  assert.match(mail.searchParams.get('body'),/Test Brand & Co/);
  assert.match(mail.searchParams.get('body'),/Public registry display requires a separate choice/);
  assert.equal(await page.locator('#brief-result script').count(),0);
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.testCopy=text;}}}));
  await page.getByRole('button',{name:'Copy brief',exact:true}).click();
  await page.waitForFunction(()=>!!window.testCopy);
  assert.match(await page.evaluate(()=>window.testCopy),/Test Brand & Co/);
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw new Error('blocked');}}}));
  await page.getByRole('button',{name:'Copy brief',exact:true}).click();
  await page.getByText('Copy is unavailable in this browser.',{exact:false}).waitFor();
  await page.locator('[name=brand]').fill('Updated Brand');
  assert.equal(await page.locator('#brief-result').isHidden(),true);
  await page.getByRole('button',{name:'Prepare my consultation brief →'}).click();
  assert.match(await page.locator('#brief-text').inputValue(),/Updated Brand/);
  await page.setViewportSize({width:390,height:844});
  await page.goto('https://geniemadeit.com/ai-influencer');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'/tmp/geniemade-influencer-mobile.png',fullPage:true});
  await page.locator('.gmn-burger').click();
  assert.equal(await page.locator('.gmn-nav a[href="/ai-influencer"]').isVisible(),true);
  await page.locator('.gmn-nav a[href="/ai-influencer"]').click();
  await page.goto('https://geniemadeit.com/');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator('.influencer-promo').screenshot({path:'/tmp/geniemade-influencer-home-mobile.png'});
  assert.equal(mutations,0,'No mutation or message request is allowed');
  // Landing-page errors are actionable; homepage stubs can be expanded if its API contract changes.
  assert.deepEqual(errors,[]);
  assert.match(readFileSync(new URL('../sitemap.xml',import.meta.url),'utf8'),/https:\/\/geniemadeit.com\/ai-influencer/);
  console.log('PASS: homepage promotion, landing image, metadata, disclaimer, consultation validation, safe mailto, copy/fallback, stale-draft invalidation, mobile menu/overflow, sitemap; zero mutations.');
  console.log('Screenshots: /tmp/geniemade-influencer-{desktop,mobile,home-desktop,home-mobile}.png');
} finally { await browser.close(); }
